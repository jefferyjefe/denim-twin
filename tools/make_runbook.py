#!/usr/bin/env python3
"""Generate the printable pilot documents FROM the shot plan, so they cannot drift from it.

A runbook typed by hand is a second copy of the capture list, and the moment a shot is added to the
specification the two disagree. The person following the paper then collects a different set of
evidence from the one the gate requires, discovers it at the gate, and has a garment on the table.

So every document here is derived: the runbook follows the same ordering the app follows, because it
calls the same `plan.order`; the measurement sheet lists what `gates.REQUIRED_MEASUREMENTS` requires;
the rig checklist lists what `gates.REQUIRED_SETUP_CHECKS` requires. `--check` fails if any of them
is out of date, and tools/verify.py runs it.

    tools/make_runbook.py [--write] [--check] [--out protocol/pilot]
"""
