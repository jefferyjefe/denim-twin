def doc_runbook(spec, shots, ordered):
    out = [BANNER, "# Pilot Capture Runbook", "",
           wrap("This follows the exact order the app gives you, because it is generated from the "
                "same ordering code. Working down this page and working through the app's NEXT "
                "ACTION are the same sequence: front-facing frames before the garment is turned "
                "over, everything that shares a camera height and lens together, all the ruler "
                "macros in one run, and the required re-lays kept apart because they are the "
                "measurement rather than an overhead."), "",
           wrap("Times are the specification's DECLARED planning figures. Nobody has yet timed this "
                "rig, and the app replaces them with your own measured pace once it has three "
                "observations of a step class. Treat the totals as an order of magnitude."), ""]
    by_state = {}
    for e in ordered:
        by_state.setdefault(e["state"], []).append(e)
    order_of = {s["state"]: s["order"] for s in spec.states}
    label_of = {s["state"]: s["label"] for s in spec.states}

    out += ["## What the whole pilot comes to", "",
            "| state | frames | required | declared time |", "|---|---|---|---|"]
    for st in sorted(by_state, key=lambda k: order_of.get(k, 99)):
        es = by_state[st]
        req = [e for e in es if e["necessity"] != "optional"]
        out.append("| %s | %d | %d | %s |"
                   % (label_of.get(st, st), len(es), len(req),
                      fmt_time(PLAN.estimate_seconds(spec, es))))
    out.append("| **total** | **%d** | **%d** | **%s** |"
               % (len(ordered), len([e for e in ordered if e["necessity"] != "optional"]),
                  fmt_time(PLAN.estimate_seconds(spec, ordered))))
    out += ["", wrap("That total is the most demanding garment the plan can describe: every "
                     "optional feature present and one instance of each. A plain pair with no "
                     "paint, no repairs and no coin pocket is materially shorter, and the app "
                     "tells you your own number after intake."), ""]

    cur = None
    for e in ordered:
        grp = (e["state"], PLAN.ORIENTATION.get(e["garment_side"], "either"),
               e["relay_generation"], e.get("camera_height_group"), e.get("lens"))
        if grp != cur:
            cur = grp
            out += ["", "### %s — %s, lay %d, %s, %s lens"
                    % (label_of.get(e["state"], e["state"]),
                       {"front_up": "FRONT up", "back_up": "BACK up",
                        "either": "either face"}[grp[1]], grp[2], grp[3], grp[4]), ""]
        bits = []
        if e.get("needs_relay_before"):
            bits.append("**LIFT AND RE-LAY FIRST**")
        if e.get("needs_camera_reposition_before"):
            bits.append("**TAKE THE PHONE OFF THE MOUNT AND REMOUNT IT**")
        if e.get("needs_second_person"):
            bits.append("**NEEDS A SECOND PERSON**")
        out.append("- [ ] `%s` (%d/%d, %s%s)%s"
                   % (e["shot_id"], e["rep"], e["rep_of"], e["necessity"],
                      ", " + e["conditional_on"] if e.get("conditional_on") else "",
                      "  " + " ".join(bits) if bits else ""))
        out.append(wrap(e["framing"], 90, "      "))
        out.append("      *why:* " + e["purpose"].replace("\n", " "))
    return "\n".join(out) + "\n"


