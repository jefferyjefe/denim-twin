def doc_rig(spec, shots, ordered):
    lines = [BANNER, "# Rig setup checklist", "",
             wrap("Every reading here is recorded by `tools/pilot.py setup`, and the cut gate "
                  "refuses to open until all of them exist and pass. They are properties of the "
                  "rig, not of the garment: freeze them once and every capture in the session "
                  "carries the hash of this configuration."), "", "## The frozen configuration", "",
             "- [ ] Camera model recorded",
             "- [ ] Mount height above the surface measured and recorded (cm)",
             "- [ ] Lens chosen for whole-garment frames and locked",
             "- [ ] Backdrop identified, and it will not change during the session",
             "- [ ] Lighting model and setting recorded",
             "- [ ] The frozen gap between the legs decided and recorded (cm)",
             "- [ ] Exposure and white balance locked",
             "- [ ] Room recorded", "", "## The calibration readings", ""]
    why = {
        "empty_backdrop": "a frame of the backdrop with nothing on it, so a mark on the cloth can "
                          "later be told from a mark on the garment",
        "board_verification": "the board photographed and detected, so the detector is known to "
                              "work on this print under this light",
        "board_square_measured": "a run of squares measured with a steel rule. The board declares "
                                 "25.0 mm; a printer that scaled to 95% puts that error into every "
                                 "measurement in the study",
        "lighting_test": "no hotspot or shadow across the area the garment will occupy",
        "exposure_white_balance": "a grey or white card photographed with the locked settings, so "
                                  "colour change through washing has a reference",
        "camera_height": "measured and recorded, because it sets the scale and the depth of field",
        "lens_selection": "chosen and locked; changing lens mid-session changes the geometry",
        "backdrop_identified": "named, so a change of backdrop is a recorded deviation",
        "daylight_controlled": "daylight excluded or constant. A session that starts at noon and "
                               "ends at dusk has two colour temperatures in it",
        "board_garment_coplanar": "a low-angle frame showing the board and the garment on one "
                                  "surface. If the board sits on a book, every scale is wrong by "
                                  "the thickness of the book",
    }
    for c in GATES.REQUIRED_SETUP_CHECKS:
        lines.append("- [ ] **%s** — %s" % (c, why.get(c, "")))
    lines += ["", wrap("The board's squares must measure %.1f mm within %.1f mm. Measure a run of "
                       "eight and divide: a single square is too short to read to that precision."
                       % (GATES.BOARD_SQUARE_MM, GATES.BOARD_SQUARE_TOLERANCE_MM)), ""]
    return "\n".join(lines)


def doc_anatomy(spec, shots, ordered):
    lines = [BANNER, "# Anatomical shot list", "",
             wrap("Every region the plan can ask for, and the frames that cover it. Regions marked "
                  "*conditional* only appear if you answered that the feature is present; a "
                  "question you have not answered is treated as PRESENT, so the frame is planned "
                  "rather than dropped."), ""]
    by_group = {}
    for r in spec.regions:
        by_group.setdefault(r["group"], []).append(r)
    shots_by_region = {}
    for e in ordered:
        shots_by_region.setdefault(e.get("region_id"), []).append(e)
    for grp in sorted(by_group):
        lines += ["", "## %s" % grp.replace("_", " "), "",
                  "| region | side | frames | changes with cut / wash |", "|---|---|---|---|"]
        for r in sorted(by_group[grp], key=lambda x: x["region_id"]):
            es = shots_by_region.get(r["region_id"], [])
            lines.append("| `%s` %s | %s | %d | %s / %s |"
                         % (r["region_id"], "*(conditional)*" if r.get("conditional_on") else "",
                            r["side"], len(es),
                            "yes" if r["can_change_by_cut"] else "no",
                            "yes" if r["can_change_by_wash"] else "no"))
    return "\n".join(lines) + "\n"


def doc_measurements(spec, shots, ordered):
    lines = [BANNER, "# Measurement sheet", "",
             wrap("Each reading is taken INDEPENDENTLY: lay the tape again, do not copy the first "
                  "number. The point of two readings is their spread, and two copies of one reading "
                  "have a spread of zero and tell you nothing. Readings that disagree by more than "
                  "the tolerance block the cut."), "",
             wrap("Conventions, from `data/garments/*/record.json`: waist, thigh and leg opening are "
                  "FULL CIRCUMFERENCES (measured flat and doubled). Rise is from the crotch seam to "
                  "the top of the waistband along the fly. Inseam is crotch seam to hem along the "
                  "inside leg. Thigh is 2.5 cm below the crotch."), "",
             "| measurement | readings needed | tolerance | 1 | 2 | 3 | mean |",
             "|---|---|---|---|---|---|---|"]
    for name, n in sorted(GATES.REQUIRED_MEASUREMENTS.items()):
        tol = GATES.MEASUREMENT_TOLERANCE.get(name, GATES.MEASUREMENT_TOLERANCE["_default_cm"])
        cells = " | ".join(["______"] * n + [""] * (3 - n))
        lines.append("| `%s` | %d | %.2f | %s | ______ |" % (name, n, tol, cells))
    lines += ["", "## Post-wash, the same dimensions again", "",
              wrap("Shrinkage is the difference between two measurements, so the after-wash set is "
                   "taken the same way, twice each, by the same method. A dimension measured "
                   "carefully before and casually after produces a shrinkage figure that is mostly "
                   "the change in method."), ""]
    for name in sorted(GATES.REQUIRED_MEASUREMENTS):
        lines.append("- [ ] `%s` after wash: ______ / ______  mean ______" % name)
    return "\n".join(lines) + "\n"


