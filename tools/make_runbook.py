def doc_post_wash(spec, shots, ordered):
    pw = [e for e in ordered if e["state"] in ("post_wash", "offcut_after")]
    lines = [BANNER, "# Post-wash checklist", "",
             wrap("Conditioning first: lay flat at room temperature for the frozen conditioning "
                  "time before any measurement. A garment measured warm out of the dryer is not the "
                  "garment the protocol describes."), "",
             "- [ ] Conditioning time elapsed and recorded",
             "- [ ] All measurements taken again, twice each (see the measurement sheet)",
             "- [ ] Garment mass re-weighed",
             "", "## Frames (%d)" % len(pw), ""]
    for e in pw:
        lines.append("- [ ] `%s` (%d/%d)" % (e["shot_id"], e["rep"], e["rep_of"]))
    lines += ["", "## Hem mapping", "",
              wrap("The macro series has to cover the WHOLE loop of each cut hem with no gap. The "
                   "app's HEM tab shows which measurement positions are covered and which are not; "
                   "a gap there is a hole in the fray profile, not a rounding detail."), ""]
    for cm in (17, 20, 25):
        g = HEM.HemGeometry.from_leg_opening("left", cm)
        lines.append("- a %d cm leg opening is a %.0f mm loop: %d positions every %.0f mm, "
                     "%d macro frames" % (cm, g.circumference_mm, len(g.positions()),
                                          g.position_spacing_mm, len(g.macros())))
    return "\n".join(lines) + "\n"


