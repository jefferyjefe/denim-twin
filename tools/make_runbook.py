def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--out", default=str(ROOT / "protocol" / "pilot"))
    a = ap.parse_args()
    spec = SPEC.load(ROOT / "protocol" / "shotplan" / "shotplan.json")
    shots, ordered = build(spec)
    out = Path(a.out)
    stale, wrote = [], []
    for name, fn in DOCS:
        text = fn(spec, shots, ordered)
        p = out / name
        if a.check:
            if not p.exists() or p.read_text() != text:
                stale.append(name)
        if a.write:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text)
            wrote.append("%s (%d lines)" % (name, text.count("\n")))
    if a.check:
        if stale:
            print("stale or missing pilot documents: %s" % ", ".join(stale))
            print("regenerate with tools/make_runbook.py --write")
            return 1
        print("pilot documents: %d, all current" % len(DOCS))
        return 0
    for w in wrote:
        print("wrote", w)
    if not a.write:
        print("nothing written; pass --write or --check")
    return 0


if __name__ == "__main__":
    sys.exit(main())
