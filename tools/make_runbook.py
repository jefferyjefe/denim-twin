BANNER = ("<!-- generated by tools/make_runbook.py from protocol/shotplan/shotplan.json. "
          "Do not edit by hand: run the tool. -->")


def wrap(s, width=94, indent=""):
    return "\n".join(textwrap.fill(line, width, initial_indent=indent,
                                   subsequent_indent=indent) or indent
                     for line in str(s).split("\n"))


def fmt_time(seconds):
    m = int(round(seconds / 60.0))
    return "%d h %02d min" % (m // 60, m % 60) if m >= 60 else "%d min" % m


def all_present_answers(spec):
    """The most demanding garment: every feature present, one instance of each counted thing."""
    return {f["key"]: (1 if f["type"] == "count" else True) for f in spec.features}


def build(spec):
    answers = all_present_answers(spec)
    shots, meta = PLAN.activate(spec, answers, {"leg_opening_cm": {"mean": 20.0}})
    ordered = PLAN.order(spec, shots)
    return shots, ordered


