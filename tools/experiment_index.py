#!/usr/bin/env python3
"""Regenerate the experiment index in experiments/README.md.

39 experiments and the index listed none of them. Several carry corrections or have been overturned
by later work (EXP_0029's causal attribution, EXP_0033's reading of the null, EXP_0037's mechanism),
and a reader with no index is most likely to find exactly those -- a superseded conclusion is worse
than no conclusion.

The generated block lives between two markers; anything written outside them is preserved. This is
the same convention weekly_scribe.py adopted after it destroyed hand-written notes.

    experiment_index.py [--check]     # --check exits 1 if the file is out of date
"""
import argparse, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
IDX = ROOT / "experiments/README.md"
BEGIN, END = "<!-- experiment-index:begin -->", "<!-- experiment-index:end -->"

# Only an explicit banner counts. A first pass keyed on words like "correction" flagged EXP_0022,
# whose title merely contains the phrase "tilt correction" -- a noun, not a supersession marker.
# So: either RETRACTED in the title, or a blockquote banner in the opening lines.
RETRACTED_TITLE = re.compile(r"\bRETRACTED\b")
BANNER = re.compile(r"^>\s*.*\b(followed up by|superseded|corrected by|retracted|"
                    r"this note was wrong|interpretation .{0,20}does not)\b", re.I | re.M)


def entry(d):
    note = d / "NOTE.md"
    if not note.exists():
        return None
    lines = note.read_text().splitlines()
    title = next((l.lstrip("# ").strip() for l in lines if l.startswith("# ")), d.name)
    head = "\n".join(lines[:14])
    hit = RETRACTED_TITLE.search(title) or BANNER.search(head)
    flag = ""
    if hit:
        own = "EXP_" + d.name.split("_")[1]
        # the pointer is the first OTHER experiment named in the banner; a self-reference is no pointer
        ref = next((r for r in re.findall(r"EXP_\d{4}", head) if r != own), None)
        flag = f" — **superseded/corrected**{f' (see {ref})' if ref else ''}"
    claims = (d / "claims.json").exists()
    return {"dir": d.name, "title": title, "flag": flag, "claims": claims}


def build():
    rows = [e for e in (entry(d) for d in sorted(ROOT.glob("experiments/EXP_*")) if d.is_dir()) if e]
    n_claimed = sum(r["claims"] for r in rows)
    out = [BEGIN, "",
           f"## Index ({len(rows)} experiments, {n_claimed} with machine-checked claims)", "",
           "Generated by `tools/experiment_index.py`; `tools/verify.py` fails if it is stale.",
           "A row marked **superseded/corrected** does not state current belief — follow its pointer.",
           ""]
    for r in rows:
        num = r["dir"].split("_")[1]
        check = " ✓" if r["claims"] else ""
        out.append(f"- **{num}** [{r['title']}]({r['dir']}/NOTE.md){check}{r['flag']}")
    out += ["", "✓ = carries a `claims.json` whose numbers `tools/check_claims.py` re-derives.", "", END]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    body = build()
    prev = IDX.read_text() if IDX.exists() else ""
    if BEGIN in prev and END in prev:
        merged = prev[:prev.index(BEGIN)] + body + prev[prev.index(END) + len(END):]
    else:
        merged = (prev.rstrip() + "\n\n" + body + "\n") if prev.strip() else body + "\n"
    if a.check:
        if merged != prev:
            print("experiments/README.md is out of date; run tools/experiment_index.py")
            return 1
        print("experiment index: up to date")
        return 0
    IDX.write_text(merged)
    print(f"experiment index: {merged.count(chr(10) + '- **')} entries written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
